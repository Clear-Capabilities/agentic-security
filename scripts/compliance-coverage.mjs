#!/usr/bin/env node
// Generates the per-control coverage maps for the bundled compliance frameworks from the framework files the engine reads, and checks
// that nothing about them can drift: the counts, the pages and the README claim about them.
//
//   node scripts/compliance-coverage.mjs --write    write docs/compliance/COVERAGE.md and a page for each framework with no hand-written one
//   node scripts/compliance-coverage.mjs            check, exit 1 on any finding (also run by `check-doc-drift.mjs --gate`)
//
// A hand-written page is kept as it is. A framework with no hand-written page gets a generated one, so no bundled framework is without a
// per-control map and a map cannot disagree with the file the engine evaluates.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_DEFAULT = path.resolve(HERE, '..');
const FRAMEWORKS_DIR = 'scanner/src/posture/compliance-frameworks';
const OUT_DIR = 'docs/compliance';

/** Pages written by hand, keyed by framework id. These are never overwritten. */
export const HAND_WRITTEN = Object.freeze({
  'nist-800-171-r3': 'nist-800-171-r3-coverage.md',
  'nist-ai-600-1': 'nist-ai-600-1-coverage.md',
  'nist-privacy-1-1': 'nist-privacy-1-1-coverage.md',
  'owasp-asvs-5': 'owasp-asvs-coverage.md',
  'owasp-llm-top-10': 'owasp-llm-top10-coverage.md',
});
export const SUMMARY_PAGE = 'COVERAGE.md';

/** The file's text, or null when it cannot be read. One read, so there is no gap between asking whether it exists and opening it. */
const readOrNull = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const TESTABLE = { yes: 'yes', partial: 'partial', no: 'no' };

export function loadFrameworks(repo = REPO_DEFAULT) {
  const dir = path.join(repo, FRAMEWORKS_DIR);
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    return { file: f, ...d };
  });
}

export function statsOf(fw) {
  const controls = Array.isArray(fw.controls) ? fw.controls : [];
  const testable = { yes: 0, partial: 0, no: 0 };
  let mapped = 0;
  for (const c of controls) {
    testable[TESTABLE[c.codeTestable] ?? 'no']++;
    if (Array.isArray(c.mapsTo) && c.mapsTo.length > 0) mapped++;
  }
  return { controls: controls.length, testable, mapped, manual: controls.length - mapped };
}

function pageName(fw) { return HAND_WRITTEN[fw.id] ?? `${fw.id}-coverage.md`; }

export function renderFrameworkPage(fw) {
  const s = statsOf(fw);
  const L = [];
  L.push(`# ${fw.name}: scanner coverage map`, '');
  L.push('<!-- generated by scripts/compliance-coverage.mjs from the framework file; do not edit by hand -->', '');
  L.push(`This page lists every control the scanner evaluates for ${fw.name}, taken from \`${FRAMEWORKS_DIR}/${fw.file}\`, the file the engine reads. It is regenerated from that file and checked for staleness, so it cannot disagree with what is assessed.`, '');
  L.push('```bash', `/compliance --walkthrough ${fw.id}`, `/compliance --report ${fw.id}`, '```', '');
  L.push(`**${s.controls} control${s.controls === 1 ? '' : 's'}** are evaluated: ${s.mapped} with an automated mapping, ${s.manual} needing a person to attest. By how much a code scan can observe: ${s.testable.yes} yes, ${s.testable.partial} partial, ${s.testable.no} no.`, '');
  if (fw.scope) L.push(`**Scope.** ${esc(fw.scope)}`, '');
  L.push('| Control | Requirement | Observable in code | Evaluated from |', '|---|---|---|---|');
  for (const c of fw.controls) {
    const from = Array.isArray(c.mapsTo) && c.mapsTo.length ? c.mapsTo.map((m) => `\`${m}\``).join(', ') : 'a person attests';
    L.push(`| \`${esc(c.id)}\` | ${esc(c.summary)} | ${esc(TESTABLE[c.codeTestable] ?? 'no')} | ${from} |`);
  }
  L.push('', '## What this does not do', '');
  L.push('<!-- limits-verified: 2026-10-20 -->', '');
  L.push('- **It is a subset.** Only the controls above are evaluated. Everything else in the framework is outside what a code scan can observe and is not assessed here.');
  L.push('- **It is evidence, not an assessment.** A control reported as present means the mapped signals are clean on the last scan. It is not an attestation, a certification or a statement of compliance.');
  L.push('- **A control needing attestation is not evidenced.** Those controls are listed so the gap is visible, and they stay open until a person attests.');
  L.push('');
  return L.join('\n');
}

export function renderSummary(fws) {
  const L = [];
  L.push('# Compliance coverage summary', '');
  L.push('<!-- generated by scripts/compliance-coverage.mjs from the framework files; do not edit by hand -->', '');
  L.push(`The scanner bundles ${fws.length} compliance frameworks. Every one has a per-control coverage map below, and each count is read from the framework file the engine evaluates, so a count here cannot drift from what is assessed. None of this is a statement that a project is compliant with, or certified against, a framework.`, '');
  L.push('| Framework | Id | Controls | Automated mapping | Needs attestation | Observable in code (yes / partial / no) | Map |', '|---|---|---|---|---|---|---|');
  let total = 0;
  for (const fw of fws) {
    const s = statsOf(fw);
    total += s.controls;
    L.push(`| ${esc(fw.name)} | \`${fw.id}\` | ${s.controls} | ${s.mapped} | ${s.manual} | ${s.testable.yes} / ${s.testable.partial} / ${s.testable.no} | [coverage](${pageName(fw)}) |`);
  }
  L.push('', `In all, ${total} controls are evaluated across ${fws.length} frameworks. The larger frameworks are partly covered: see each map's scope line for what is left out.`, '');
  return L.join('\n');
}

/** What should be on disk: path (relative to the repo) -> content. Hand-written pages are not in this set. */
export function expectedFiles(repo = REPO_DEFAULT) {
  const fws = loadFrameworks(repo);
  const out = {};
  out[path.join(OUT_DIR, SUMMARY_PAGE)] = renderSummary(fws);
  for (const fw of fws) if (!HAND_WRITTEN[fw.id]) out[path.join(OUT_DIR, pageName(fw))] = renderFrameworkPage(fw);
  return out;
}

export function checkCoverage(repo = REPO_DEFAULT) {
  const findings = [];
  const fws = loadFrameworks(repo);
  for (const [rel, want] of Object.entries(expectedFiles(repo))) {
    const have = readOrNull(path.join(repo, rel));
    if (have === null) { findings.push({ file: rel, message: 'missing; run node scripts/compliance-coverage.mjs --write' }); continue; }
    if (have !== (want.endsWith('\n') ? want : want + '\n')) findings.push({ file: rel, message: 'stale; run node scripts/compliance-coverage.mjs --write' });
  }
  for (const fw of fws) {
    if (HAND_WRITTEN[fw.id] && readOrNull(path.join(repo, OUT_DIR, HAND_WRITTEN[fw.id])) === null) findings.push({ file: path.join(OUT_DIR, HAND_WRITTEN[fw.id]), message: `the hand-written page for ${fw.id} is missing` });
  }
  // the README states how many frameworks there are and how many have a map
  const readme = fs.readFileSync(path.join(repo, 'README.md'), 'utf8');
  const m = /for (\d+) bundled frameworks, with per-control coverage maps for (all|\d+)/.exec(readme);
  if (!m) findings.push({ file: 'README.md', message: 'the compliance line no longer states the framework count and map coverage in the form this check reads' });
  else {
    if (Number(m[1]) !== fws.length) findings.push({ file: 'README.md', message: `states ${m[1]} bundled frameworks; there are ${fws.length}` });
    const mapped = fws.filter((fw) => readOrNull(path.join(repo, OUT_DIR, pageName(fw))) !== null).length;
    const claimed = m[2] === 'all' ? fws.length : Number(m[2]);
    if (claimed !== mapped) findings.push({ file: 'README.md', message: `states per-control maps for ${m[2]}; ${mapped} of ${fws.length} exist` });
  }
  return findings;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  if (write) {
    for (const [rel, content] of Object.entries(expectedFiles())) {
      fs.writeFileSync(path.join(REPO_DEFAULT, rel), content.endsWith('\n') ? content : content + '\n');
      console.log(`wrote ${rel}`);
    }
  }
  const findings = checkCoverage();
  if (findings.length) {
    for (const f of findings) console.error(`compliance-coverage: ${f.file}: ${f.message}`);
    process.exit(1);
  }
  console.log('compliance-coverage: every bundled framework has a per-control map, the maps match the framework files, and the README counts are right.');
}
