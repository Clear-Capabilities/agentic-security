#!/usr/bin/env node
// Renders the two generated reference pages of the assurance documentation (DOC-001) from the code's own registries.
//
//   node scripts/render-assurance-docs.mjs           # rewrite docs/reference/{mcp-tool-contract,assurance-capability-matrix}.md
//   node scripts/render-assurance-docs.mjs --check   # exit 1 when either page differs from what the registries produce
//
// Nothing in the pages is typed by hand: the tool list and classifications come from the MCP registry and the capability tool
// table, the oracle rows from the oracle manifest, the feature rows from the assurance configuration, the invariant rows from the
// scenario module, the enforcement rows from the capability probes. A tool added, a platform status changed or a feature
// reclassified makes the check fail until the page is regenerated. The pages state limits as the code states them and add no
// claim of their own.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const S = (p) => import(pathToFileURL(join(ROOT, 'scanner', 'src', p)).href);
export const PAGES = Object.freeze({
  mcp: 'docs/reference/mcp-tool-contract.md',
  matrix: 'docs/reference/assurance-capability-matrix.md',
});

const row = (cells) => `| ${cells.join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
// prose in this repository avoids the em-dash; registry text is rewritten, never edited in place
const plain = (s) => String(s ?? '').replace(/\s+—\s+/g, ', ').replace(/—/g, ', ').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
const firstSentence = (s) => { const t = plain(s); const m = /^(.+?[.!?])(\s|$)/.exec(t); return m ? m[1] : t; };
const code = (s) => `\`${s}\``;

export async function renderMcp() {
  const { ALL_TOOLS } = await S('mcp/tools.js');
  const { TOOL_CAPABILITIES } = await S('capabilities/tool-registry.js');
  const tools = [...ALL_TOOLS].sort((a, b) => a.name.localeCompare(b.name));
  const classified = tools.map((t) => ({ t, c: TOOL_CAPABILITIES[t.name] ?? null }));
  const count = (e) => classified.filter((x) => x.c?.effect === e).length;
  const unclassified = classified.filter((x) => !x.c).map((x) => x.t.name);
  const rows = classified.map(({ t, c }) => {
    const props = t.inputSchema?.properties ?? {};
    const req = new Set(t.inputSchema?.required ?? []);
    const inputs = Object.keys(props).map((k) => (req.has(k) ? `${code(k)}*` : code(k))).join(', ') || 'none';
    return [code(t.name), c ? c.effect : '**unclassified**', c ? c.requires.map(code).join(', ') : 'n/a', inputs, firstSentence(t.description), plain(c?.note ?? '')];
  });
  return [
    '# MCP tool contract',
    '',
    '<!-- generated by scripts/render-assurance-docs.mjs; do not edit by hand. Regenerate with `npm run docs:assurance` in scanner/. -->',
    '',
    `The MCP server registers ${tools.length} tools. This page is generated from the registry (${code('scanner/src/mcp/tools.js')}) and from the capability classification of each tool (${code('scanner/src/capabilities/tool-registry.js')}), and a test compares the two in both directions, so a tool cannot be added without being classified here.`,
    '',
    `| Classification | Tools |`,
    `| --- | --- |`,
    `| read | ${count('read')} (reads local state only) |`,
    `| mutating | ${count('mutating')} (writes project or agent state, or runs project code) |`,
    `| external | ${count('external')} (reaches, or may reach, the network through a package manager) |`,
    `| unclassified | ${unclassified.length}${unclassified.length ? ` (${unclassified.join(', ')})` : ''} |`,
    '',
    'An asterisk marks a required input. "Checks before handler" lists the capability checks the tool gate makes first when the gate is active (an operator-supplied capability policy, or the operator enabling capability enforcement in the environment; a project file can never turn it on). A tool missing from the classification table is refused when the gate is active.',
    '',
    table(['Tool', 'Classification', 'Checks before handler', 'Inputs', 'What it does', 'Classification note'], rows),
    '',
    '## What the classification means, and what it does not',
    '',
    '- The classification is policy at the tool boundary. A tool runs in the MCP server process, so the decision is `in-process-policy`, never enforced isolation. Only the capability runner mediates a task\'s files, commands and network, and the capability pages say where it is verified.',
    `- ${code('invariant_scenario_export')} and ${code('portfolio_progress')} are read tools: they build an export or a progress view from files confined to the session root and execute nothing. They are off unless the operator enabled ${code('invariant-scenarios')} or ${code('portfolio-assurance')} respectively.`,
    '- The mutating and external tools (`apply_fix`, `apply_sca_upgrade`, `verify_fix`, `append_scratchpad`, `append_agents_memory`, `synthesize_sca_upgrade`) always require the tool and session-root checks when the gate is active. Whether the tool gate is active at all is an operator decision.',
    '',
    '## Evidence',
    '',
    '- Registry and classification agree in both directions: [scanner/test/capabilities/tools.test.js](../../scanner/test/capabilities/tools.test.js).',
    '- The tool inventory and hardening notes: [scanner/src/mcp/CLAUDE.md](../../scanner/src/mcp/CLAUDE.md).',
    '- This page equals the generator output: [scanner/test/documentation/generated-pages.test.js](../../scanner/test/documentation/generated-pages.test.js).',
    '',
  ].join('\n');
}

export async function renderMatrix() {
  const { FEATURES } = await S('posture/assurance/config.js');
  const { oracleManifest } = await S('posture/oracles/registry.js');
  const { ADAPTER_NAMES } = await S('lineage/deployment/ingest.js');
  const { INVARIANT_CLASSES, LIMITS: INV_LIMITS } = await S('posture/invariants/schema.js');
  const { HARD_BOUNDS, KINDS_BY_CLASS } = await S('posture/invariants/scenarios.js');
  const { platformStatements, CAPABILITY_CONTROLS } = await S('capabilities/probes.js');
  const { REPORT_LIMITATIONS } = await S('capabilities/report.js');
  const man = oracleManifest();

  const features = Object.entries(FEATURES).map(([id, f]) => [code(id), f.risk, f.platforms.join(', '), plain(f.platformNote ?? 'none')]);
  const platform = (o, p) => `${o.platforms[p].status}`;
  const oracles = man.oracles.map((o) => [
    code(o.id), o.class, o.version, o.prerequisites.map((p) => code(p.id)).join(', '),
    platform(o, 'darwin'), platform(o, 'linux'), platform(o, 'win32'), o.requiresFeature ? code(o.requiresFeature) : 'verification-oracles',
    `[${o.fixtures.dir.replace(/^test\/fixtures\//, '')}](../../scanner/${o.fixtures.dir})`,
  ]);
  const nonTaint = man.nonTaint.classes.map((c) => [code(c.id), code(c.oracle), plain(c.claim), `[fixtures](../../scanner/${c.fixtures.dir})`]);
  const unsupported = man.nonTaint.unsupported.map((u) => [code(u.id), u.cwes.join(', '), plain(u.reason)]);

  const guide = existsSync(join(ROOT, 'docs/guides/deployment-aware-support.md')) ? readFileSync(join(ROOT, 'docs/guides/deployment-aware-support.md'), 'utf8') : '';
  const validated = Object.fromEntries([...guide.matchAll(/^\| `([a-z-]+)` \| (validated|not validated) \|/gm)].map((m) => [m[1], m[2]]));
  const adapters = ADAPTER_NAMES.map((n) => [code(n), validated[n] ?? 'unknown (no row in the deployment guide)']);

  const invariants = INVARIANT_CLASSES.map((c) => [code(c), (KINDS_BY_CLASS[c] ?? []).map(code).join(', ') || 'none']);
  const platforms = platformStatements();
  const enforcement = Object.entries(platforms).map(([p, s]) => [p, s.backend ?? 'none', code(s.status), plain(s.note)]);

  return [
    '# Assurance capability matrix',
    '',
    '<!-- generated by scripts/render-assurance-docs.mjs; do not edit by hand. Regenerate with `npm run docs:assurance` in scanner/. -->',
    '',
    'Scope of the verification, deployment, invariant and capability-enforcement features, read from the code that implements them. A cell says what the repository has executed, not what it hopes to support. "Supported" for a platform means the repository\'s own tests were executed there; "unverified" means no outcome is claimed; "unsupported" means the feature refuses to run. Every feature below is off by default and the high-risk ones are operator-only.',
    '',
    '## Features, risk class and platforms',
    '',
    table(['Feature', 'Risk class', 'Platforms where it can run at all', 'Platform note'], features),
    '',
    '## Runtime oracles: class, prerequisites and platform status',
    '',
    `Oracle targets are small JavaScript modules run under Node (the ${code('node-runtime')} prerequisite) inside the trust boundary. That is the whole language scope of the oracles: detector support for the nine core languages and for Haskell and Nix is a separate matter, listed in [language support](../language-support.md), and detector support alone does not imply oracle support. An unmet prerequisite is reported ${code('unsupported')} and the target never runs.`,
    '',
    table(['Oracle', 'Class', 'Version', 'Prerequisites', 'macOS', 'Linux', 'Windows', 'Feature', 'Fixtures'], oracles),
    '',
    '### Non-taint vulnerability classes',
    '',
    table(['Class', 'Executed by', 'Claim it can test', 'Evidence'], nonTaint),
    '',
    'Named as unsupported, with the reason:',
    '',
    table(['Class', 'CWEs', 'Reason'], unsupported),
    '',
    '## Deployment adapters',
    '',
    'An adapter is validated for deployment-aware claims only when the frozen synthetic ablation holds a positive and a negative fixture for it and no baseline defect was lost. The status column is read from the validated-adapters table in [deployment-aware support](../guides/deployment-aware-support.md), which a test compares with the evaluation itself.',
    '',
    table(['Adapter', 'Status'], adapters),
    '',
    '## Invariants: classes, scenario kinds and bounds',
    '',
    table(['Invariant class', 'Scenario kinds generated'], invariants),
    '',
    `Hard bounds on a generated scenario (a request over a ceiling is rejected, not clamped): ${Object.entries(HARD_BOUNDS).map(([k, v]) => `${code(k)} ${v}`).join(', ')}. Contract document limits: ${Object.entries(INV_LIMITS).map(([k, v]) => `${code(k)} ${v}`).join(', ')}.`,
    '',
    'Limits of the invariant tooling, as the guide states them: the application is a factory over an in-memory store (durable state in a real database, queue or file system is not observed); concurrency is cooperative scheduling in one process; a clean result covers only the declared bounded scenarios; a proposed or inferred contract is advisory until a named human approves it. See [business-logic invariants](../guides/business-logic-invariants.md).',
    '',
    '## Enforced-capability backend',
    '',
    table(['Platform', 'Backend', 'Status', 'Note'], enforcement),
    '',
    `Controls proved by active probes before an enforced task runs: ${CAPABILITY_CONTROLS.map(code).join(', ')}. An enforced task is released only on an advertised backend with every control it depends on proved; a control that is not proved blocks the run and the target never executes.`,
    '',
    'Standing limitations, stated in every capability report:',
    '',
    ...REPORT_LIMITATIONS.map((l) => `- ${plain(l)}`),
    '',
    '## Evidence',
    '',
    '- Oracle adapters, conformance and tamper controls: [scanner/test/verification/oracle-conformance.test.js](../../scanner/test/verification/oracle-conformance.test.js) and [guide](../guides/verification-oracle-conformance.md).',
    '- Deployment adapters and the frozen ablation: [scanner/test/deployment/differentiation-ablation.test.js](../../scanner/test/deployment/differentiation-ablation.test.js).',
    '- Invariant scenarios and the held-out benchmark: [scanner/test/invariants/invariant-scenarios.test.js](../../scanner/test/invariants/invariant-scenarios.test.js).',
    '- Capability enforcement and the adversarial corpus: [scanner/test/capabilities/adversarial.test.js](../../scanner/test/capabilities/adversarial.test.js) and [scanner/src/capabilities/CLAUDE.md](../../scanner/src/capabilities/CLAUDE.md).',
    '- This page equals the generator output: [scanner/test/documentation/generated-pages.test.js](../../scanner/test/documentation/generated-pages.test.js).',
    '',
  ].join('\n');
}

export async function renderAll() {
  return { [PAGES.mcp]: await renderMcp(), [PAGES.matrix]: await renderMatrix() };
}

/** The pages whose current text differs from what the registries produce. `read` is injectable so a test can show a stale page is caught. */
export async function stalePages(read = (rel) => (existsSync(join(ROOT, rel)) ? readFileSync(join(ROOT, rel), 'utf8') : null)) {
  const pages = await renderAll();
  return Object.entries(pages).filter(([rel, text]) => read(rel) !== text).map(([rel]) => rel);
}

async function main() {
  const check = process.argv.includes('--check');
  const pages = await renderAll();
  let stale = 0;
  for (const [rel, text] of Object.entries(pages)) {
    const abs = join(ROOT, rel);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (check) {
      if (current !== text) { console.error(`${rel} is stale; run: npm run docs:assurance`); stale++; }
    } else if (current !== text) { writeFileSync(abs, text); console.log(`wrote ${rel}`); } else console.log(`unchanged ${rel}`);
  }
  if (check) { console.log(stale ? `${stale} generated page(s) are stale` : 'generated assurance pages match the registries'); process.exit(stale ? 1 : 0); }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
