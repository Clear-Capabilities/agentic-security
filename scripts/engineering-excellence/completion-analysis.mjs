#!/usr/bin/env node
// Why did a target not complete? (E6-02) Reads the committed artifacts that record non-completion and puts every one into exactly one cause, by what its own
// message says. A target that never ran is not a scan failure; a harness that lost its output is not an engine crash; a timeout is not an out-of-memory.
// Anything the patterns do not recognise is reported as `unclassified` with its text, never folded into a known cause.
//
//   node scripts/engineering-excellence/completion-analysis.mjs [--verify]   (writes docs/engineering-excellence/THIRD_PARTY_COMPLETION.{md,json})
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const CAUSES = Object.freeze({
  not_attempted_unpinned: { owner: 'setup', meaning: 'the target has no pinned commit, so nothing was cloned or scanned' },
  clone_or_fetch: { owner: 'setup', meaning: 'the source could not be obtained' },
  missing_tool: { owner: 'setup', meaning: 'a program the scan needs was not available' },
  unsupported_language: { owner: 'engine', meaning: 'the engine does not handle the language' },
  parsing: { owner: 'engine', meaning: 'the file could not be parsed or lowered to the IR' },
  harness_capture: { owner: 'harness', meaning: 'the scan finished but its output was not captured intact' },
  timeout: { owner: 'engine', meaning: 'the scan exceeded its time budget' },
  out_of_memory: { owner: 'engine', meaning: 'the scan ran out of memory' },
  engine_crash: { owner: 'engine', meaning: 'the scan process exited with an error or an exception' },
  unclassified: { owner: 'unknown', meaning: 'the recorded reason matches no known cause' },
});

/** The cause named by a recorded reason. Order matters: the most specific patterns come first. */
export function classifyReason(text) {
  const t = String(text || '');
  if (/has no pinned commit/i.test(t)) return 'not_attempted_unpinned';
  if (/scan produced no result block|truncated or interleaved capture|not parseable as JSON/i.test(t)) return 'harness_capture';
  if (/out of memory|heap|ENOMEM|\bOOM\b|allocation failed/i.test(t)) return 'out_of_memory';
  if (/exceeded \d+\s*ms|no result within|timed out|timeout/i.test(t)) return 'timeout';
  if (/could not resolve host|clone|ls-remote|fetch failed|authentication failed|repository not found|ref not found/i.test(t)) return 'clone_or_fetch';
  if (/command not found|ENOENT.*(git|python|java|go|node)\b|not installed|missing tool|is not available/i.test(t)) return 'missing_tool';
  if (/unsupported (language|extension)|no confinement primitive/i.test(t)) return 'unsupported_language';
  if (/no-function-lowered|parse error|syntax error|unexpected token|could not be parsed/i.test(t)) return 'parsing';
  if (/scan exited|crash|TypeError|ReferenceError|RangeError|stack overflow|uncaught/i.test(t)) return 'engine_crash';
  return 'unclassified';
}

const readJson = (p) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8')); } catch { return null; } };

export function collect() {
  const rows = [];
  const proof = readJson('bench/proof-corpus/results/summary.json');
  for (const t of (proof && proof.targets) || []) {
    if (t.status === 'ok') continue;
    rows.push({ population: 'third-party corpus (committed summary)', id: t.id, reason: t.error || t.reason || t.status });
  }
  const runPointer = readJson('bench/independent/runs/BASELINE.json');
  const runId = runPointer && (runPointer.runId || runPointer.run);
  const run = runId ? readJson(`bench/independent/runs/${runId}/RESULT.json`) : null;
  for (const u of (run && run.unscored) || []) rows.push({ population: `independent baseline ${runId} (unscored)`, id: u.id, reason: u.reason });
  const f = runId ? readJson(`bench/independent/runs/${runId}/forensics.json`) : null;
  const fRows = Array.isArray(f && f.classifications) ? f.classifications : [];
  for (const c of fRows) if (c.stage === 'scan-execution') rows.push({ population: `independent baseline ${runId} (forensics re-scan)`, id: c.entryId, reason: (c.evidence && c.evidence.failureReason) || c.reason });
  return { rows: rows.map((r) => ({ ...r, cause: classifyReason(r.reason) })), runId: runId || null, scored: run && run.coverage ? run.coverage.scored : null };
}

export function render(c) {
  const byPop = new Map();
  for (const r of c.rows) { const m = byPop.get(r.population) || new Map(); m.set(r.cause, (m.get(r.cause) || 0) + 1); byPop.set(r.population, m); }
  const lines = ['# Why targets did not complete (E6-02)', '', 'Generated by `node scripts/engineering-excellence/completion-analysis.mjs` from the committed result files. Each non-completed target is placed in exactly one cause by what its own recorded reason says; a reason that matches no pattern is `unclassified`, never folded into a known cause.', '',
    '| Cause | Owner | Meaning |', '|---|---|---|', ...Object.entries(CAUSES).map(([k, v]) => `| ${k} | ${v.owner} | ${v.meaning} |`), ''];
  for (const [pop, m] of byPop) {
    lines.push(`## ${pop}`, '', '| Cause | Targets |', '|---|---|', ...[...m.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} |`), '');
  }
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const c = collect(); const md = render(c);
  const mdPath = path.join(ROOT, 'docs', 'engineering-excellence', 'THIRD_PARTY_COMPLETION.md'); const jsonPath = path.join(ROOT, 'docs', 'engineering-excellence', 'data', 'completion-analysis.json');
  const json = JSON.stringify({ schema: 'agentic-security/completion-analysis@1', runId: c.runId, rows: c.rows }, null, 2) + '\n';
  if (process.argv.includes('--verify')) { const same = fs.existsSync(mdPath) && fs.readFileSync(mdPath, 'utf8') === md && fs.readFileSync(jsonPath, 'utf8') === json; console.log(same ? 'completion analysis: up to date' : 'completion analysis: STALE'); process.exit(same ? 0 : 1); }
  fs.mkdirSync(path.dirname(jsonPath), { recursive: true }); fs.writeFileSync(mdPath, md); fs.writeFileSync(jsonPath, json);
  console.log(`wrote ${path.relative(ROOT, mdPath)}: ${c.rows.length} non-completed targets`);
}
