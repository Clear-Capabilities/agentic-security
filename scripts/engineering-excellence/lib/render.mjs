// Terminal and Markdown views of the program status. Pure functions of (manifest, status document, clock): no I/O here.
import { STALE_HEARTBEAT_MS } from './model.mjs';
import { summarize } from './store.mjs';

const bar = (pct, width = 20) => {
  const filled = Math.round((Math.max(0, Math.min(100, pct)) / 100) * width);
  return `[${'#'.repeat(filled)}${'.'.repeat(width - filled)}]`;
};

export function formatDuration(ms) {
  if (ms == null || !Number.isFinite(ms) || ms < 0) return 'unknown';
  const s = Math.floor(ms / 1000);
  const h = String(Math.floor(s / 3600)).padStart(2, '0');
  const m = String(Math.floor((s % 3600) / 60)).padStart(2, '0');
  return `${h}:${m}:${String(s % 60).padStart(2, '0')}`;
}

export function renderText(manifest, doc, { now = Date.now(), epic = null } = {}) {
  const s = summarize(manifest, doc, { now });
  const L = [];
  const co = doc.checkout || {};
  L.push('AGENTIC SECURITY - ENGINEERING EXCELLENCE');
  L.push(`Checkout: ${co.commit ? co.commit.slice(0, 10) : 'unknown'} (${co.branch || 'unknown branch'})   Worktree: ${co.dirty == null ? 'unknown' : co.dirty ? 'dirty' : 'clean'}   Updated: ${doc.updatedAt}`);
  L.push(`Program: ${bar(s.weightedPercent)} ${s.weightedPercent.toFixed(1)}% verified (weighted)   ${s.verified} of ${s.total} tasks verified`);
  L.push(`Tasks: ${s.counts.done} done | ${s.counts.in_progress} active | ${s.counts.pending} pending | ${s.counts.blocked} blocked | ${s.counts.already_satisfied} already satisfied | ${s.counts.failed} failed`);
  for (const e of s.epics) {
    if (epic && e.id !== epic) continue;
    L.push(`${e.id} ${e.title.slice(0, 44).padEnd(44)} ${String(e.verified).padStart(2)}/${String(e.total).padEnd(2)} verified ${bar(e.percent, 10)} ${String(e.percent).padStart(3)}%`);
  }
  if (epic) {
    for (const t of manifest.tasks.filter((x) => x.epic === epic)) {
      const st = doc.tasks[t.id];
      L.push(`  ${t.id} ${st.state.padEnd(17)} ${t.title}`);
    }
  }
  for (const a of s.active) {
    const hb = a.stale ? `   HEARTBEAT STALE (${formatDuration(a.heartbeatAgeMs)} old)` : '';
    L.push(`NOW: ${a.id} ${a.title}${a.command ? ` - running: ${a.command.slice(0, 80)}` : ''} (elapsed ${formatDuration(a.elapsedMs)})${hb}`);
  }
  if (!s.active.length) L.push('NOW: nothing in progress');
  for (const b of s.blocked) L.push(`BLOCKED: ${b.id} ${b.reason || ''}${b.nextAction ? ` | next: ${b.nextAction}` : ''}`);
  for (const f of s.failed) L.push(`FAILED: ${f.id} ${f.reason || ''}`);
  L.push(`LAST VERIFIED: ${s.lastVerified ? `${s.lastVerified.id} ${s.lastVerified.title} (${s.lastVerified.at})` : 'none yet'}`);
  L.push(`NEXT: ${s.next.length ? s.next.join(' | ') : 'none ready (see BLOCKED and dependencies)'}`);
  L.push('ETA: unknown (no measured completion estimate)');
  return L.join('\n');
}

export function renderFailures(manifest, doc) {
  const L = [];
  for (const t of manifest.tasks) {
    const st = doc.tasks[t.id];
    if (st.state === 'blocked') L.push(`${t.id} BLOCKED (${st.blocker?.kind || 'unspecified'}): ${st.blocker?.reason}\n  next action: ${st.blocker?.nextAction || '(none recorded)'}`);
    else if (st.state === 'failed') L.push(`${t.id} FAILED: ${st.failure?.reason}`);
    else continue;
    const bad = [...st.commands].reverse().filter((c) => c.outcome !== 'exited' || c.exitCode !== 0).slice(0, 3);
    for (const c of bad) L.push(`  command: ${c.argv.join(' ').slice(0, 140)}\n    outcome ${c.outcome}${c.exitCode == null ? '' : `, exit ${c.exitCode}`}${c.log ? `, log ${c.log}` : ''}`);
  }
  return L.length ? L.join('\n') : 'No blocked or failed tasks.';
}

export function renderMarkdown(manifest, doc, { now = Date.now() } = {}) {
  const s = summarize(manifest, doc, { now });
  const co = doc.checkout || {};
  const L = [];
  L.push('# Engineering Excellence status', '');
  L.push('> Generated by `node scripts/engineering-excellence/status.mjs --markdown`. Do not edit by hand; the source of truth is `scripts/engineering-excellence/status.json`.', '');
  L.push(`- Checkout: \`${co.commit || 'unknown'}\` on \`${co.branch || 'unknown'}\`, worktree ${co.dirty == null ? 'unknown' : co.dirty ? '**dirty** (measurements from it are not release evidence)' : 'clean'}`);
  L.push(`- Updated: ${doc.updatedAt} (revision ${doc.revision})`);
  L.push(`- Program: **${s.weightedPercent.toFixed(1)}%** verified (weighted by priority), ${s.verified} of ${s.total} tasks verified`);
  L.push(`- Counts: ${s.counts.done} done, ${s.counts.already_satisfied} already satisfied, ${s.counts.in_progress} in progress, ${s.counts.pending} pending, ${s.counts.blocked} blocked, ${s.counts.failed} failed`);
  L.push('- ETA: unknown (no measured completion estimate)', '');
  L.push('| Epic | Verified | Percent |', '|---|---|---|');
  for (const e of s.epics) L.push(`| ${e.id} ${e.title} | ${e.verified}/${e.total} | ${e.percent}% |`);
  L.push('');
  for (const e of manifest.epics) {
    L.push(`## ${e.id} ${e.title}`, '', '| Task | State | Attempts | Verified by |', '|---|---|---|---|');
    for (const t of manifest.tasks.filter((x) => x.epic === e.id)) {
      const st = doc.tasks[t.id];
      const by = st.evidence ? `${st.evidence.testCommands.length} test run(s), commit \`${(st.evidence.sourceCommit || '').slice(0, 10)}\`` : st.blocker ? `blocked: ${st.blocker.reason}` : st.failure ? `failed: ${st.failure.reason}` : '';
      L.push(`| ${t.id} ${t.title} | ${st.state} | ${st.attempts} | ${by.replace(/\|/g, '/')} |`);
    }
    L.push('');
  }
  return L.join('\n');
}

export { STALE_HEARTBEAT_MS };
