#!/usr/bin/env node
// Builds the evidence contract inventory (E7-01) from the product's own producers: for each evidence kind, a real sample is produced, described,
// inspected, wrapped in an EvidenceRef and verified. Writes docs/engineering-excellence/evidence-contracts.json and EVIDENCE_CONTRACTS.md. `--verify`
// regenerates in memory and exits 1 when the committed files differ.
//
//   node scripts/engineering-excellence/evidence-inventory.mjs [--verify]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSamples } from './lib/evidence-samples.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const reg = await import(path.join(ROOT, 'scanner', 'src', 'posture', 'assurance', 'evidence-registry.js'));
const { samples, notExercised } = await buildSamples();
const snapshot = reg.buildSnapshotRef({ commit: 'a'.repeat(40), engineVersion: 'inventory', configDigest: 'sha256:' + '0'.repeat(64) });

const rows = [];
for (const kind of reg.EVIDENCE_KIND_NAMES) {
  const k = reg.EVIDENCE_KINDS[kind];
  const row = { kind, title: k.title, producer: k.producer, producerExists: fs.existsSync(path.join(ROOT, k.producer)), signedBy: k.signed, snapshotBinding: k.snapshot };
  const sample = samples[kind];
  if (!sample) { rows.push({ ...row, exercised: false, reason: notExercised[kind] || 'no sample' }); continue; }
  const d = reg.describeEvidence(kind, sample); const insp = reg.inspectEvidence(kind, sample);
  const observed = reg.observeSnapshotBinding(sample);
  const ref = reg.buildEvidenceRef(kind, sample, snapshot);
  const verified = reg.verifyEvidenceRef(ref, sample, snapshot);
  rows.push({ ...row, exercised: true, schema: d.schema, version: d.version, identity: d.id ? 'present' : 'by content digest', observedSnapshotBinding: observed, bindingMatchesDeclaration: observed === k.snapshot, usable: insp.ok, errors: insp.errors, gaps: insp.gaps, evidenceRefVerifies: verified.ok });
}
const json = { schema: 'agentic-security/evidence-contracts@1', evidenceRefSchema: reg.EVIDENCE_REF_SCHEMA, evidenceRefVersion: reg.EVIDENCE_REF_VERSION, kinds: rows };

const cell = (v) => String(v ?? '').replace(/\|/g, '/');
const md = [
  '# Evidence contracts (E7-01)', '',
  'Generated by `npm run ee:evidence-contracts` from real records built by each producer. Do not edit by hand; `--verify` fails when this file is stale.', '',
  'Each row is one kind of evidence. **Schema** and **version** are read from the record by the registry, whatever convention the producer used. **Snapshot binding** is how the format itself refers to the code it describes today; `none` means it does not, and the `EvidenceRef` wrapper supplies the missing binding without changing the producer.', '',
  '| Kind | Schema | Version | Identity | Snapshot binding | Signed | Exercised | Gaps |', '|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.kind} | ${cell(r.schema ?? (r.exercised ? 'none declared' : 'n/a'))} | ${cell(r.version ?? '')} | ${r.exercised ? r.identity : 'n/a'} | ${r.exercised ? r.observedSnapshotBinding : r.snapshotBinding}${r.exercised && !r.bindingMatchesDeclaration ? ' (declared ' + r.snapshotBinding + ')' : ''} | ${r.signedBy} | ${r.exercised ? 'yes' : 'no: ' + cell(r.reason)} | ${r.exercised ? cell((r.gaps || []).join('; ') || 'none') : ''} |`),
  '', `${rows.filter((r) => r.exercised).length} of ${rows.length} kinds were exercised with a real record; every exercised record produced an \`EvidenceRef\` that verifies against it.`,
  '', 'The git origin of a finding is `findingProvenance`; a bare `provenance` property on a finding belongs to other features. The reference for a finding records each under its own name and never merges them.', '',
].join('\n');

const jsonPath = path.join(ROOT, 'docs', 'engineering-excellence', 'evidence-contracts.json');
const mdPath = path.join(ROOT, 'docs', 'engineering-excellence', 'EVIDENCE_CONTRACTS.md');
const jsonText = JSON.stringify(json, null, 2) + '\n';
if (process.argv.includes('--verify')) {
  const same = fs.existsSync(jsonPath) && fs.readFileSync(jsonPath, 'utf8') === jsonText && fs.existsSync(mdPath) && fs.readFileSync(mdPath, 'utf8') === md;
  console.log(same ? 'evidence contracts: up to date' : 'evidence contracts: STALE, run npm run ee:evidence-contracts');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(jsonPath, jsonText); fs.writeFileSync(mdPath, md);
console.log(`wrote ${path.relative(ROOT, jsonPath)} and ${path.relative(ROOT, mdPath)}: ${rows.filter((r) => r.exercised).length}/${rows.length} kinds exercised`);
