#!/usr/bin/env node
// Records, in the repository, which PRD requirements the supervised loop has NOT verified (docs/completion-status.json).
//
// The loop's own state lives in the git-ignored .loop-engineering/, so a hosted runner cannot see it. This writes the part a reader
// and the release gate need: the percentage, the denominators and every open requirement with its unmet criteria and why. The release
// check (scripts/release-check.mjs `completion-declared`) refuses a release that has open requirements unless its changelog section
// says "Partial release" and names them.
//
//   node scripts/write-completion-status.mjs            # reads `run.mjs status --json`, writes docs/completion-status.json
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const r = spawnSync(process.execPath, [join(ROOT, 'scripts', 'loop-engineering', 'run.mjs'), 'status', '--json'], { cwd: ROOT, encoding: 'utf8' });
if (r.status !== 0) { console.error(r.stderr || r.stdout); process.exit(1); }
const s = JSON.parse(r.stdout);
const open = s.requirements.filter((x) => x.state !== 'verified' && x.id !== 'REL-001');
const out = {
  schema: 1,
  note: 'Generated by scripts/write-completion-status.mjs from the loop controller. REL-001 (the final stable-tree acceptance) is listed whenever the others are open, because it cannot pass first.',
  verifiedPercent: s.verifiedPercent,
  requirements: { verified: s.requirements.filter((x) => x.state === 'verified').length, total: s.requirements.length },
  remaining: s.requirements.filter((x) => x.state !== 'verified').map((x) => ({
    id: x.id, title: x.title, state: x.state, unmetCriteria: x.unmetCriteria || [],
    blocker: (x.blockers && x.blockers[0] && (x.blockers[0].detail || x.blockers[0].type)) || (x.id === 'REL-001' ? 'final-phase acceptance: needs a live controller and every other requirement verified' : (x.lastFailure || 'not verified')),
  })),
};
void open;
writeFileSync(join(ROOT, 'docs', 'completion-status.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`docs/completion-status.json: ${out.requirements.verified}/${out.requirements.total} verified, ${out.remaining.length} open`);
