#!/usr/bin/env node
// Score the deterministic context analysis on bench/dci-real-app/cases.mjs and write docs/engineering-excellence/DCI_REAL_APP.md + data/dci-real-app.json.
//   node bench/dci-real-app/runner.mjs          run and write
//   node bench/dci-real-app/runner.mjs --check  run and fail when the committed outputs differ
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildContext } from '../../scanner/src/context-intelligence/build.js';
import { normalizeConfig } from '../../scanner/src/context-intelligence/config.js';
import { evaluateInvariants } from '../../scanner/src/context-intelligence/invariants.js';
import { CASES, NOT_REPRESENTABLE, POLICIES } from './cases.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const OUT_JSON = path.join(ROOT, 'docs/engineering-excellence/data/dci-real-app.json');
const OUT_MD = path.join(ROOT, 'docs/engineering-excellence/DCI_REAL_APP.md');
const NOW = new Date('2026-10-16T00:00:00Z');
const PKG = { express: '{"name":"p","version":"1.0.0","dependencies":{"express":"4.18.0"}}', flask: '{"name":"p","version":"1.0.0"}' };

export async function scoreCase(c) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dci-real-'));
  try {
    fs.writeFileSync(path.join(root, 'package.json'), PKG[c.stack]);
    for (const [f, t] of Object.entries(c.files)) fs.writeFileSync(path.join(root, f), t);
    const built = await buildContext(root, { config: normalizeConfig({}).config });
    const policy = { schema: 'agentic-security/dci-invariants', schemaVersion: '1.0.0', invariants: [POLICIES[{ authentication: 'authentication', 'authorization-role': 'role', ownership: 'ownership', 'tenant-scope': 'tenant' }[c.control]](c.glob)] };
    const res = evaluateInvariants(policy, built.bundles, { now: NOW }).results;
    const seen = new Set(); const rows = [];
    for (const [route, label] of Object.entries(c.routes)) {
      const hit = res.filter((r) => r.label === route);
      const verdicts = [...new Set(hit.map((r) => r.verdict))].sort();
      const verdict = !hit.length ? 'not_found' : verdicts.includes('violated') ? 'violated' : verdicts.includes('satisfied') && verdicts.length === 1 ? 'satisfied' : verdicts.join('+');
      seen.add(route);
      rows.push({ route, label, verdict, outcome: label === 'vulnerable' ? (verdict === 'violated' ? 'tp' : verdict === 'satisfied' ? 'fn' : 'unresolved') : (verdict === 'violated' ? 'fp' : verdict === 'satisfied' ? 'tn' : 'unresolved') });
    }
    const extra = res.filter((r) => !seen.has(r.label)).map((r) => ({ route: r.label, verdict: r.verdict }));
    return { id: c.id, stack: c.stack, family: c.family, nonObvious: !!c.nonObvious, why: c.why, rows, unlabelledRoutes: extra };
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
}

const rate = (n, d) => (d === 0 ? null : Number((n / d).toFixed(4)));
function tally(rows) {
  const t = { tp: 0, fp: 0, fn: 0, tn: 0, unresolved: 0 }; for (const r of rows) t[r.outcome]++;
  return { ...t, routes: rows.length, precision: rate(t.tp, t.tp + t.fp), recall: rate(t.tp, t.tp + t.fn), precisionOf: t.tp + t.fp, recallOf: t.tp + t.fn };
}

export async function run() {
  const scored = []; for (const c of CASES) scored.push(await scoreCase(c));
  const flat = scored.flatMap((s) => s.rows.map((r) => ({ ...r, case: s.id, stack: s.stack, family: s.family, nonObvious: s.nonObvious })));
  const group = (key) => Object.fromEntries([...new Set(flat.map((r) => r[key]))].sort().map((k) => [k, tally(flat.filter((r) => r[key] === k))]));
  return { schema: 'agentic-security/dci-real-app@1', labelledBy: 'the author of the cases, not an independent reviewer; no case is from an upstream advisory; all are synthetic', cases: scored.length, routes: flat.length, overall: tally(flat), byStack: group('stack'), byFamily: group('family'), byNonObvious: group('nonObvious'),
    perCase: scored, misses: flat.filter((r) => r.outcome === 'fn' || r.outcome === 'fp' || r.outcome === 'unresolved').map((r) => ({ case: r.case, stack: r.stack, family: r.family, route: r.route, label: r.label, verdict: r.verdict, outcome: r.outcome })), notRepresentable: NOT_REPRESENTABLE };
}

const pct = (v) => (v === null ? 'n/a' : `${(v * 100).toFixed(0)}%`);
const line = (name, t) => `| ${name} | ${t.routes} | ${t.tp} | ${t.fp} | ${t.fn} | ${t.tn} | ${t.unresolved} | ${pct(t.precision)} (${t.tp}/${t.precisionOf}) | ${pct(t.recall)} (${t.tp}/${t.recallOf}) |`;
export function render(r) {
  const head = '| | routes | TP | FP | FN | TN | unresolved | precision | recall |\n|---|---|---|---|---|---|---|---|---|';
  const L = ['# Deterministic context analysis on application-shaped authorization cases (E4-06)', '', 'Generated by `node bench/dci-real-app/runner.mjs`; checked by `--check`. The cases are in `bench/dci-real-app/cases.mjs`.', '',
    '## Read this first', '', `- **Who labelled the cases:** ${r.labelledBy}. The PRD asks for labels from an independent reviewer or an upstream advisory; this corpus does not meet that. Treat every number below as a measurement on ${r.cases} small hand-written applications, **not** as accuracy on real software.`,
    '- Each route is labelled `vulnerable` or `safe` from what the code means, and the labels were fixed before the run. A `safe` route is either the fixed twin of a vulnerable one or a deliberately non-obvious counterexample (a control applied somewhere a simple scan does not look).',
    '- A route the analysis could not settle is counted as `unresolved`, which is neither a hit nor a miss; precision and recall are over the settled routes. Nothing was dropped from the denominators.', '',
    `## Overall (${r.routes} routes in ${r.cases} cases)`, '', head, line('all', r.overall), '', '## By stack', '', head, ...Object.entries(r.byStack).map(([k, t]) => line(k, t)), '',
    '## By family', '', head, ...Object.entries(r.byFamily).map(([k, t]) => line(k, t)), '', '## Non-obvious routes versus plain ones', '', head, ...Object.entries(r.byNonObvious).map(([k, t]) => line(k === 'true' ? 'non-obvious' : 'plain', t)), '',
    '## Every route the analysis got wrong or could not settle', '', '| case | stack | family | route | label | verdict | outcome |', '|---|---|---|---|---|---|---|', ...r.misses.map((m) => `| ${m.case} | ${m.stack} | ${m.family} | \`${m.route}\` | ${m.label} | ${m.verdict} | ${m.outcome} |`), '',
    '## Families the analysis cannot represent', '', ...r.notRepresentable.map((n) => `- **${n.family}:** ${n.reason}.`), '', '## Confidence', '',
    'Each count above is over a handful of routes, so no interval narrower than "could be almost anything" is justified; the per-family denominators are printed beside every rate so the size of the evidence is visible. No confidence interval is computed because the cases are not a random sample of anything.', ''];
  return L.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await run(); const json = JSON.stringify(r, null, 2) + '\n'; const md = render(r);
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT_JSON) && fs.readFileSync(OUT_JSON, 'utf8') === json && fs.existsSync(OUT_MD) && fs.readFileSync(OUT_MD, 'utf8') === md;
    if (!same) { console.error('dci-real-app outputs are stale: run node bench/dci-real-app/runner.mjs'); process.exit(1); }
    console.log('dci-real-app outputs are current'); process.exit(0);
  }
  fs.writeFileSync(OUT_JSON, json); fs.writeFileSync(OUT_MD, md); console.log(md.split('\n').slice(10, 20).join('\n'));
}
