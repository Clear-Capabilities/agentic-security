#!/usr/bin/env node
// Vendors java-parser's resolved dependency closure into vendor/java-parser/,
// published via `files` and referenced at runtime through the "#java-parser"
// subpath import — instead of a plain `dependencies` entry.
//
// WHY THIS EXISTS
// ----------------
// java-parser -> chevrotain hard-pins an old, vulnerable lodash/lodash-es
// (<=4.17.23, no upstream fix). scanner/package.json's `overrides` field
// forces the safe ^4.18.1 for THIS repo's own install, but npm overrides
// never apply to a package's own consumers — a real `npm install` of the
// published package would still pull the vulnerable versions if java-parser
// were a normal `dependencies` entry.
//
// `bundleDependencies` looks like the standard fix (ship the already-resolved,
// override-applied tree inside the tarball), but combining it with `overrides`
// hangs npm's resolver (confirmed: `bundleDependencies` alone and `overrides`
// alone both resolve in well under a second; together, `npm install`/`npm ci`
// spins indefinitely, burning CPU, on this npm version). So instead:
// java-parser lives in `devDependencies` (resolved normally, with the override
// applied, for this repo's own dev/build environment only — never installed
// for a consumer), this script copies that already-resolved, already-safe
// tree into vendor/java-parser/node_modules/, and the one call site
// (src/sast/java-ast-folding.js) imports it via the "#java-parser" subpath
// import (package.json `imports` field) instead of a bare `java-parser`
// specifier, so nothing ever asks npm to resolve `java-parser` for a
// consumer's install at all.
//
// vendor/ is gitignored (like node_modules/) and regenerated by this script,
// which `npm run build` always runs first — so the published dist/ bundle
// (ncc-inlined) and the published src/ (library `exports`) both stay in sync
// with whatever is actually resolved right now.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCANNER = path.resolve(HERE, '..');
const SRC_NODE_MODULES = path.join(SCANNER, 'node_modules');
const VENDOR_ROOT = path.join(SCANNER, 'vendor', 'java-parser', 'node_modules');

// The full resolved closure java-parser needs at runtime: itself, chevrotain
// (+ its own scoped @chevrotain/* packages and chevrotain-allstar), and the
// two packages the `overrides` field exists to fix.
const PACKAGES = [
  'java-parser',
  'chevrotain',
  'chevrotain-allstar',
  'lodash',
  'lodash-es',
];
const SCOPED_DIRS = ['@chevrotain'];

function copyDir(src, dest) {
  fs.rmSync(dest, { recursive: true, force: true });
  fs.cpSync(src, dest, { recursive: true, dereference: true });
}

function main() {
  if (!fs.existsSync(path.join(SRC_NODE_MODULES, 'java-parser'))) {
    console.error(
      'vendor-java-parser: node_modules/java-parser not found — run `npm install` first.',
    );
    process.exit(1);
  }

  fs.rmSync(path.join(SCANNER, 'vendor', 'java-parser'), { recursive: true, force: true });
  fs.mkdirSync(VENDOR_ROOT, { recursive: true });

  const copied = [];
  for (const name of PACKAGES) {
    const src = path.join(SRC_NODE_MODULES, name);
    if (!fs.existsSync(src)) {
      console.error(`vendor-java-parser: node_modules/${name} not found — dependency tree changed?`);
      process.exit(1);
    }
    copyDir(src, path.join(VENDOR_ROOT, name));
    copied.push(name);
  }
  for (const scope of SCOPED_DIRS) {
    const src = path.join(SRC_NODE_MODULES, scope);
    if (!fs.existsSync(src)) continue; // optional — only chevrotain's own scoped deps
    copyDir(src, path.join(VENDOR_ROOT, scope));
    copied.push(scope);
  }

  // Verify the two packages the override exists for actually landed at the
  // safe version — if this ever silently regresses (a lockfile change, a
  // dropped override), fail loudly here rather than shipping the vulnerable
  // version again.
  const SAFE_MIN = '4.18.1';
  for (const name of ['lodash', 'lodash-es']) {
    const pkgJson = JSON.parse(
      fs.readFileSync(path.join(VENDOR_ROOT, name, 'package.json'), 'utf8'),
    );
    if (pkgJson.version !== SAFE_MIN) {
      console.error(
        `vendor-java-parser: node_modules/${name} resolved to ${pkgJson.version}, expected ` +
          `${SAFE_MIN} (the overrides-forced safe version). Refusing to vendor a vulnerable copy — ` +
          'check scanner/package.json "overrides".',
      );
      process.exit(1);
    }
  }

  // Node refuses an `imports`/`exports` target that resolves through a path
  // containing a `node_modules` segment (package-encapsulation rule) — so
  // the "#java-parser" subpath import can't point directly at
  // vendor/java-parser/node_modules/java-parser/src/index.js, even though
  // that exact path is what java-parser's own "exports" map allows. A plain
  // relative import from ordinary source (not a package.json imports/exports
  // target) has no such restriction, so this thin re-export file — sitting
  // outside any node_modules directory — is the entry point instead.
  fs.writeFileSync(
    path.join(SCANNER, 'vendor', 'java-parser', 'entry.mjs'),
    "export * from './node_modules/java-parser/src/index.js';\n" +
      "export { default } from './node_modules/java-parser/src/index.js';\n",
  );

  // stderr, not stdout: this script runs as part of the "prepare" lifecycle
  // hook, which also fires during `npm pack`/`npm publish` — anything on
  // stdout there corrupts `npm pack --json`'s output for whoever is parsing
  // it (this repo's own release-check.mjs included).
  console.error(`vendor-java-parser: vendored ${copied.join(', ')} into vendor/java-parser/node_modules/`);
}

main();
