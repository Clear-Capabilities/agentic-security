// How much of the work of attributing findings to commits was actually possible, and how much of that was done (E7-02).
//
// A single "attributed / total" rate mixes two different things: findings the pipeline could have attributed and did not (a gap in the pipeline), and findings no
// pipeline could attribute (a file git ignores, generated code, a file git does not track, a checkout with no history). Counting the second kind as failures
// punishes the tool for the repository, and hiding them inflates the rate. This module keeps them apart and states both denominators:
//
//   attributed             complete: a commit introduced it. uncommitted: it is in the working tree and in no commit yet (resolved, but not to a commit)
//   ineligible             ignored, generated, untracked, or history-unavailable (no repository, git failed, or a shallow clone cut the history short)
//   eligible, unattributed the pipeline could have and did not, with its reason: budget_exhausted, project-wide (a whole-project analysis that a
//                          single-file replay cannot reproduce), unconfirmed (the finding's condition was not confirmed in the history it could see),
//                          not_available, or error
//
// `eligibleRate` = attributed / (attributed + eligible unattributed). It is a rate over what attribution could reach, and it is reported next to `overallRate`
// (attributed / all) so neither can stand in for the other. The target of 95% is aspirational: `targetStatus` says `met`, `not_met`, or
// `insufficient_eligible` when there are too few eligible findings (under 30) for a rate to mean anything. Nothing here invents an author or a date.
import * as cp from 'node:child_process';
import * as path from 'node:path';
import { hardenGitArgs, hardenGitEnv } from '../../util/git-hardening.js';

export const ATTRIBUTION_TARGET = 0.95;
export const MIN_ELIGIBLE_FOR_RATE = 30;
export const ATTRIBUTION_CATEGORIES = Object.freeze([
  'attributed', 'uncommitted',
  'ineligible:ignored', 'ineligible:generated', 'ineligible:untracked', 'ineligible:history-unavailable',
  'eligible:budget_exhausted', 'eligible:project-wide', 'eligible:unconfirmed', 'eligible:not_available', 'eligible:error',
]);

// Findings made by a pass over the WHOLE project (a declared set of states found in one file and violated in another, a race between two files, a prompt
// stored in one file and used in another, a call between services). Replaying a single file at an old commit cannot reproduce them, so the origin walk ends
// "never confirmed" for every one. They are reported under their own name because the remedy (a project-scoped replay) is different from the remedy for
// an ordinary unconfirmed finding.
const PROJECT_WIDE_PARSERS = new Set(['STATE-MACHINE', 'CONCURRENCY', 'LLM-STORED-PROMPT-XFILE', 'CROSS-SERVICE', 'CROSS-REPO']);
const PROJECT_WIDE_FAMILIES = new Set(['spec-drift', 'state-machine-bypass', 'concurrency-bug']);

const GENERATED_PATH = /(?:^|\/)(?:generated|gen|__generated__|dist|build|vendor|node_modules)\/|\.min\.(?:js|css)$|\.pb\.(?:go|js|ts|py)$|_pb2(?:_grpc)?\.py$|\.g\.dart$|\.generated\.\w+$/i;
const GENERATED_HEADER = /@generated\b|\bDO NOT EDIT\b|\bCode generated by\b|\bauto-?generated\b.*\bdo not (?:edit|modify)\b/i;

const git = (root, args, input) => {
  try { return { ok: true, out: cp.execFileSync('git', hardenGitArgs(args), { cwd: root, encoding: 'utf8', input, timeout: 30000, stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024, env: hardenGitEnv() }) }; }
  catch (e) { return { ok: false, out: '', error: e }; }
};

/** What git says about a set of files: tracked, ignored, and whether there is usable history. @param {string[]} files paths relative to `root` */
export function inspectRepository(root, files) {
  const inside = git(root, ['rev-parse', '--is-inside-work-tree']);
  if (!inside.ok || inside.out.trim() !== 'true') return { repo: false, shallow: false, tracked: new Set(), ignored: new Set() };
  const shallow = git(root, ['rev-parse', '--is-shallow-repository']).out.trim() === 'true';
  const head = git(root, ['rev-parse', '--verify', 'HEAD']);
  const prefix = git(root, ['rev-parse', '--show-prefix']).out.trim();
  const tracked = new Set(git(root, ['ls-files', '-z']).out.split('\0').filter(Boolean).map((p) => (prefix && p.startsWith(prefix) ? p.slice(prefix.length) : p)));
  const ignored = new Set();
  const list = [...new Set(files)].filter((f) => !tracked.has(f));
  if (list.length) {
    const r = git(root, ['check-ignore', '--stdin', '-z'], list.join('\0') + '\0');
    for (const p of r.out.split('\0').filter(Boolean)) ignored.add(p);
  }
  return { repo: true, shallow, hasHead: head.ok, tracked, ignored };
}

const normalise = (root, f) => { const rel = path.isAbsolute(f) ? path.relative(root, f) : f; return rel.split(path.sep).join('/'); };

/**
 * @param {object[]} findings findings carrying `file` and `findingProvenance`
 * @param {{root:string, readHeader?:(file:string)=>string|null, repo?:object}} ctx `readHeader` returns the first lines of a file (for generated-code markers)
 * @returns {{categories:Object<string,number>, total:number, attributed:number, ineligible:number, eligible:number, eligibleUnattributed:number, overallRate:number|null,
 *            eligibleRate:number|null, target:number, targetStatus:string, perFinding:{id:string, file:string|null, category:string, reason:string|null}[]}}
 */
export function attributionCoverage(findings, { root, readHeader = null, repo = null } = {}) {
  const list = Array.isArray(findings) ? findings : [];
  const files = list.map((f) => (f && typeof f.file === 'string' ? normalise(root || '.', f.file) : null)).filter(Boolean);
  const info = repo || inspectRepository(root || '.', files);
  const categories = Object.fromEntries(ATTRIBUTION_CATEGORIES.map((c) => [c, 0]));
  const perFinding = [];
  for (const f of list) {
    const file = f && typeof f.file === 'string' ? normalise(root || '.', f.file) : null;
    const fp = f && f.findingProvenance;
    const status = fp && fp.status;
    let category; let reason = null;
    if (status === 'complete') category = 'attributed';
    else if (status === 'uncommitted') category = 'uncommitted';
    else if (!info.repo) { category = 'ineligible:history-unavailable'; reason = 'the directory is not inside a git work tree'; }
    else if (file && info.ignored.has(file)) { category = 'ineligible:ignored'; reason = 'git ignores this file'; }
    else if (file && (GENERATED_PATH.test(file) || (readHeader && GENERATED_HEADER.test(readHeader(file) || '')))) { category = 'ineligible:generated'; reason = 'the file is generated code, not authored'; }
    else if (file && !info.tracked.has(file)) { category = 'ineligible:untracked'; reason = 'git does not track this file'; }
    else if (info.hasHead === false) { category = 'ineligible:history-unavailable'; reason = 'the repository has no commits'; }
    else if (info.shallow && (status === 'partial' || status === 'not_available') && fp && fp.historyCoverage && fp.historyCoverage.shallow === true) { category = 'ineligible:history-unavailable'; reason = 'a shallow clone cut the history short'; }
    else if (status === 'budget_exhausted') { category = 'eligible:budget_exhausted'; reason = (fp.limitations || [])[0] || 'the analysis budget ran out'; }
    else if (status === 'partial' && (PROJECT_WIDE_PARSERS.has(f.parser) || PROJECT_WIDE_FAMILIES.has(f.family))) { category = 'eligible:project-wide'; reason = 'the finding comes from a whole-project analysis; replaying one file at an old commit cannot reproduce it'; }
    else if (status === 'partial') { category = 'eligible:unconfirmed'; reason = (fp.limitations || [])[0] || 'the finding was not confirmed in the history that could be seen'; }
    else if (status === 'error') { category = 'eligible:error'; reason = (fp.limitations || [])[0] || 'resolution failed'; }
    else { category = 'eligible:not_available'; reason = (fp && (fp.limitations || [])[0]) || 'no provenance was recorded for this finding'; }
    categories[category]++;
    perFinding.push({ id: String((f && (f.stableId || f.id)) ?? ''), file, category, reason });
  }
  const total = list.length;
  const attributed = categories.attributed + categories.uncommitted;
  const ineligible = Object.entries(categories).filter(([k]) => k.startsWith('ineligible:')).reduce((a, [, n]) => a + n, 0);
  const eligibleUnattributed = Object.entries(categories).filter(([k]) => k.startsWith('eligible:')).reduce((a, [, n]) => a + n, 0);
  const eligible = attributed + eligibleUnattributed;
  const eligibleRate = eligible === 0 ? null : Number((attributed / eligible).toFixed(4));
  const targetStatus = eligible < MIN_ELIGIBLE_FOR_RATE ? 'insufficient_eligible' : eligibleRate >= ATTRIBUTION_TARGET ? 'met' : 'not_met';
  return { categories, total, attributed, ineligible, eligible, eligibleUnattributed, overallRate: total === 0 ? null : Number((attributed / total).toFixed(4)), eligibleRate, target: ATTRIBUTION_TARGET, targetStatus, perFinding };
}
